import { userFromRequest, unauthorizedResponse } from "../../../../../../lib/auth/require-user";
import { getAgentRun } from "../../../../../../lib/v4/dashboard";

export const dynamic = "force-dynamic";

export async function GET(request: Request, context: { params: Promise<{ runId: string }> }) {
  const user = userFromRequest(request);
  if (!user) return unauthorizedResponse();
  const { runId } = await context.params;
  const run = await getAgentRun(user.userId, runId);
  return run ? Response.json(run) : Response.json({ error: { code: "NOT_FOUND", message: "Agent run not found." } }, { status: 404 });
}

export async function POST(request: Request, context: { params: Promise<{ runId: string }> }) {
  const user = userFromRequest(request);
  if (!user) return unauthorizedResponse();
  void context;
  return Response.json({ error: { code: "SERVER_OWNED", message: "Agent steps are generated by the server-side runner." } }, { status: 403 });
}
